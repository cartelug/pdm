/* ==========================================================================
   wfe-theme — folds the Walk for Education colour theme into the stylesheets the pages already load
   --------------------------------------------------------------------------
   usage: node scripts/wfe-theme.mjs          rewrite the marked block in each target stylesheet
          node scripts/wfe-theme.mjs --check  fail if a target is out of date

   src/design/wfe-theme.css is the single source. A separate stylesheet would cost every phone one more
   render-blocking request (about a second of largest-contentful-paint on the throttled speed profile), so the
   same rules are appended, between markers, to the home family's css/wfe-campaign.css and the inner pages'
   css/wfe-editorial.css. Every rule is scoped to body.wfe-campaign, so nothing else on the site is affected.
   ========================================================================== */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "src/design/wfe-theme.css"), "utf8").trimEnd();
const targets = ["css/wfe-campaign.css", "css/wfe-editorial.css"];
const start =
  "/* wfe-theme:start (generated by scripts/wfe-theme.mjs from src/design/wfe-theme.css; do not edit here) */";
const end = "/* wfe-theme:end */";
const block = `${start}\n\n${source}\n\n${end}\n`;
const check = process.argv.includes("--check");
let stale = 0;

for (const target of targets) {
  const file = path.join(root, target);
  const css = fs.readFileSync(file, "utf8");
  const from = css.indexOf(start);
  const to = css.indexOf(end);
  const next =
    from === -1
      ? `${css.trimEnd()}\n\n${block}`
      : `${css.slice(0, from)}${block}${css.slice(to + end.length).replace(/^\n/, "")}`;
  if (next === css) continue;
  if (check) {
    console.error(`${target} is out of date: run npm run theme`);
    stale++;
  } else {
    fs.writeFileSync(file, next);
    console.log(`${target} updated`);
  }
}
if (check && stale) process.exit(1);
if (check) console.log("Walk theme is in sync in " + targets.length + " stylesheets.");
