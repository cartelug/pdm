/* ==========================================================================
   tokens — generate the design-token stylesheet from src/design/tokens.json
   --------------------------------------------------------------------------
   usage: node scripts/tokens.mjs            write the three generated stylesheets
          node scripts/tokens.mjs --check    fail when a generated file is out of date or
                                             a core brand colour is missing from today's CSS

   Outputs
     src/design/generated/tokens.css  tokens only
     src/design/generated/fonts.css   @font-face rules for the Astro build (bundler paths)
     css/brand.css                    fonts and tokens for the hand-written pages (public paths)
   Brands are selected with data-brand="pci" or data-brand="walk"; with no attribute the master
   brand (PCI) applies.
   ========================================================================== */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "src/design/tokens.json");
const OUT_TOKENS = path.join(ROOT, "src/design/generated/tokens.css");
const OUT_FONTS = path.join(ROOT, "src/design/generated/fonts.css");
const OUT_BRAND = path.join(ROOT, "css/brand.css");
const check = process.argv.includes("--check");

const tokens = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
const problems = [];

const HEX = /^#[0-9a-f]{6}$/i;
const rgbChannels = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");

const brandNames = Object.keys(tokens.brands);
const reference = Object.keys(tokens.brands[brandNames[0]].colour).sort();
for (const [brand, definition] of Object.entries(tokens.brands)) {
  const names = Object.keys(definition.colour).sort();
  if (names.join() !== reference.join())
    problems.push(`${brand} does not define the same colour names as ${brandNames[0]}`);
  for (const [name, value] of Object.entries(definition.colour)) {
    if (!HEX.test(value)) problems.push(`${brand}.${name} must be a six-digit hex colour, found ${value}`);
  }
}
for (const name of tokens.brandCore) {
  if (!reference.includes(name)) problems.push(`brandCore lists ${name}, which is not a colour token`);
}

function brandBlock(selector, definition) {
  const { colour, alpha } = definition;
  const ink = rgbChannels(colour.ink);
  const lines = [];
  // Stylelint wants #fff, not #ffffff, wherever a colour can be written short.
  const short = (hex) => (/^#(.)\1(.)\2(.)\3$/i.test(hex) ? `#${hex[1]}${hex[3]}${hex[5]}` : hex);
  for (const [name, value] of Object.entries(colour)) lines.push(`--c-${name}: ${short(value)};`);
  lines.push(`--c-line: rgb(${ink} / ${alpha.line}%);`);
  lines.push(`--c-line-strong: rgb(${ink} / ${alpha["line-strong"]}%);`);
  lines.push(`--c-on-deep-muted: rgb(${rgbChannels(colour["on-deep"])} / ${alpha["on-deep-muted"]}%);`);
  lines.push(`--shadow-1: 0 1px 2px rgb(${ink} / 6%), 0 8px 24px -12px rgb(${ink} / 18%);`);
  lines.push(`--shadow-2: 0 2px 4px rgb(${ink} / 8%), 0 22px 48px -18px rgb(${ink} / 34%);`);
  lines.push(`--shadow-3: 0 30px 70px -20px rgb(${ink} / 40%);`);
  return `${selector} {\n${lines.join("\n")}\n}`;
}

function sharedBlock() {
  const { fonts, type, space, layout, radius, layers, motion } = tokens;
  const lines = [
    `--font-head: "${fonts.head.family}", "${fonts.head.family} Fallback", ${fonts.fallback};`,
    `--font-body: "${fonts.body.family}", "${fonts.body.family} Fallback", ${fonts.fallback};`,
  ];
  for (const [name, value] of Object.entries(type))
    lines.push(`--${name === "measure" ? "measure" : `fs-${name}`}: ${value};`);
  for (const [name, value] of Object.entries(space)) lines.push(`--s-${name}: ${value}px;`);
  lines.push(`--gutter: ${layout.gutter};`, `--shell: ${layout.shell};`, `--section: ${layout.section};`);
  for (const [name, value] of Object.entries(radius)) lines.push(`--r-${name}: ${value};`);
  for (const [name, value] of Object.entries(layers)) lines.push(`--z-${name}: ${value};`);
  for (const [name, value] of Object.entries(motion.duration)) lines.push(`--t-${name}: ${value};`);
  for (const [name, value] of Object.entries(motion.ease)) lines.push(`--ease-${name}: ${value};`);
  return `:root {\n${lines.join("\n")}\n}`;
}

const { sm, md, lg } = tokens.breakpoints;
const header = `/* GENERATED by scripts/tokens.mjs from src/design/tokens.json (version ${tokens.version}). Do not edit by hand.

   Breakpoints cannot be custom properties inside @media. They are fixed here, once, for both brands:
   ${sm}px, ${md}px and ${lg}px (min-width only). Any other @media width is a defect.

   Brands: data-brand="pci" or data-brand="walk" on <html>. PCI is the default. */`;

// One @font-face per face, a metric-matched fallback per face, and one alias face per legacy family name. The
// aliases let the older stylesheets, which name fonts directly (and which are protected), resolve to the two house
// files instead of downloading anything else.
function fontFaces(source) {
  const { head, body, aliases } = tokens.fonts;
  const faces = [];
  const weights = (face) => `${Math.min(...face.weights)} ${Math.max(...face.weights)}`;
  // Stylelint wants single-word family names unquoted.
  const named = (family) => (/^[A-Za-z][A-Za-z0-9-]*$/.test(family) ? family : `"${family}"`);
  const declare = (family, face) =>
    `@font-face {
      font-family: ${named(family)};
      font-style: normal;
      font-weight: ${weights(face)};
      font-display: swap;
      src: url("${source(face)}") format("woff2");${face.sizeAdjust && face.sizeAdjust !== "100%" ? `\nsize-adjust: ${face.sizeAdjust};` : ""}
    }`;
  for (const font of [head, body]) {
    for (const face of font.faces) faces.push(declare(font.family, face));
    for (const face of font.faces) {
      const fb = face.fallback;
      faces.push(`@font-face {
      font-family: "${font.family} Fallback";
      font-weight: ${weights(face)};
      src: ${fb.local.map((name) => `local("${name}")`).join(", ")};
      size-adjust: ${fb.sizeAdjust};
      ascent-override: ${fb.ascentOverride};
      descent-override: ${fb.descentOverride};
      line-gap-override: ${fb.lineGapOverride};
    }`);
    }
  }
  for (const [role, names] of Object.entries(aliases))
    for (const family of names) for (const face of tokens.fonts[role].faces) faces.push(declare(family, face));
  return faces.join("\n\n");
}

const tokenCss = [
  sharedBlock(),
  brandBlock(':root,\n[data-brand="pci"]', tokens.brands.pci),
  brandBlock('[data-brand="walk"]', tokens.brands.walk),
].join("\n\n");

const generated = {
  [OUT_TOKENS]: [header, tokenCss].join("\n\n"),
  [OUT_FONTS]: [
    "/* GENERATED by scripts/tokens.mjs from src/design/tokens.json. Do not edit by hand. Font faces for the Astro build. */",
    fontFaces((face) => `../../../${face.file}`),
  ].join("\n\n"),
  [OUT_BRAND]: [header, fontFaces((face) => `../${face.file}`), tokenCss].join("\n\n"),
};

const formatted = {};
for (const [file, text] of Object.entries(generated)) {
  const options = (await prettier.resolveConfig(file)) ?? {};
  formatted[file] = await prettier.format(text, { ...options, filepath: file });
}

// Every core brand colour must already exist in the live stylesheets, so adopting the tokens
// recolours nothing. Colours new to this system (for example on-success) are not core.
function stylesheets(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return stylesheets(full);
    return entry.name.endsWith(".css") && full !== OUT_BRAND ? [full] : [];
  });
}
const corpus = [path.join(ROOT, "css"), path.join(ROOT, "src/styles")]
  .flatMap(stylesheets)
  .map((file) => fs.readFileSync(file, "utf8").toLowerCase())
  .join("\n");

const unmatched = [];
const introduced = [];
for (const [brand, definition] of Object.entries(tokens.brands)) {
  for (const [name, value] of Object.entries(definition.colour)) {
    if (corpus.includes(value.toLowerCase())) continue;
    (tokens.brandCore.includes(name) ? unmatched : introduced).push(`${brand}.${name} ${value}`);
  }
}
for (const entry of unmatched) problems.push(`core brand colour ${entry} is not used by any current stylesheet`);

if (check) {
  for (const [file, text] of Object.entries(formatted)) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (current !== text) problems.push(`${path.relative(ROOT, file)} is out of date; run npm run tokens`);
  }
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  console.log(
    `Design tokens v${tokens.version}: generated files are current, every core brand colour exists in today's CSS` +
      (introduced.length ? `; new to the system: ${introduced.join(", ")}.` : "."),
  );
} else {
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  for (const [file, text] of Object.entries(formatted)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`Wrote ${path.relative(ROOT, file)} (tokens v${tokens.version}).`);
  }
}
